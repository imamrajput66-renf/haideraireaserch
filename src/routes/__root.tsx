function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event, session) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      if (event === "SIGNED_IN" && session?.user) {
        const key = `hair-login-${session.user.id}-${session.access_token.slice(-12)}`;
        if (!sessionStorage.getItem(key)) {
          sessionStorage.setItem(key, "1");
          void supabase.from("login_events").insert({
            user_id: session.user.id,
            email: session.user.email ?? null,
            event: "sign_in",
            user_agent: navigator.userAgent.slice(0, 200),
          });
        }
      }
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  const path = useRouterState({ select: (s) => s.location.pathname });
  const [showChat, setShowChat] = useState(false);
  useEffect(() => {
    const w = window as Window & { requestIdleCallback?: (cb: () => void) => number };
    if (w.requestIdleCallback) w.requestIdleCallback(() => setShowChat(true));
    else setTimeout(() => setShowChat(true), 1500);
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      <Outlet />
      <Toaster />
      {showChat && path !== "/assistant" && !path.startsWith("/auth") && (
        <Suspense fallback={null}><ChatWidget /></Suspense>
      )}
    </QueryClientProvider>
  );
}
